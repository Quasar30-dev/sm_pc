"""Size Matters: which strength tier each enemy class reads from its level's combat table. Research aid.

The level module's combat table (LEVEL_02 0x22ed80; found by its first row) has, per level, three hit point tiers
(+0, +4, +8), their challenge mode values, and three attack tiers (+0x20, +0x24, +0x28) with theirs. A class reads
its tiers by address in its own code (`Pygmy` init 0x1b33b0: table + 0 = tier 0 hit points). This scans a level's
decompilation for those addresses and attributes each to the class whose callbacks reach the reading function
(through unnamed functions only, three calls deep).

    python tools/sm/sm_enemy_tiers.py 02            # print
    python tools/sm/sm_enemy_tiers.py --emit        # write src/sm/enemy_tiers.inl from every decompiled level
"""
import json
import re
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
WORK = ROOT / 'build/sm_pc_work'
FIRST = struct.pack('<8f', 1, 3, 5, 0, 48, 192, 288, 0)
# Read by hand where the attribution by code place picks a neighbour: {(level, class): (hit point tier, attack tier)}
OVERRIDES = {
    (1, 'TrainingBot'): (1, 2),   # its attack is read in TrainingBotShrapnel's run (0x1c2f78, table + 0x28)
}


def module_bytes(level):
    index = json.loads((ROOT / 'mods/sm_native/oracle-v3/index.json').read_text())
    entry = next(e for e in index['disc_files'] if e['disc_path'] == f'/LVL/LEVEL_{level}.REL')
    with open(index['source_iso'], 'rb') as f:
        f.seek(entry['disc_lba'] * index['sector_size'])
        return f.read(entry['file_size'])


def scan(level):
    table = module_bytes(level).find(FIRST)
    functions = json.loads((WORK / f'ghidra/L{level}_decomp.json').read_text(encoding='utf-8', errors='replace'))['functions']
    reads = {}                                           # function name -> set of table offsets
    for f in functions:
        for m in re.finditer(r'(?:0x|DAT_00)([0-9a-f]{6})\b', f['c']):
            a = int(m.group(1), 16)
            if table <= a < table + 0x30:
                reads.setdefault(f['name'], set()).add(a - table)
    # A reading function belongs to the class whose callbacks it lies among: a class's code is one run of the
    # module (its helpers are reached through state tables, so the call graph does not tie them to it).
    records = json.loads((WORK / f'classes_{level}.json').read_text())['records']
    spans = []
    for r in records:
        code = [c for c in r['callbacks'] if c]          # the four main callbacks: the extra ones can be shared code
        if code:
            spans.append((code, r['name']))
    entry = {f['name']: int(f['entry'], 16) for f in functions}
    classes = {}
    for name, offsets in reads.items():
        at = entry[name]
        if at >= 0x1000000:
            continue
        code, owner = min(spans, key=lambda s: min(abs(at - c) for c in s[0]))
        if min(abs(at - c) for c in code) > 0x3000:
            continue                                     # shared engine code (the hero's own damage), not a class's
        health, attack = classes.setdefault(owner, (set(), set()))
        health |= {o // 4 for o in offsets if o < 0x10}
        attack |= {(o - 0x20) // 4 for o in offsets if 0x20 <= o < 0x30}
    # An attack tier read in a neighbouring class's code (a shot, a spike, shrapnel) is the attack of the nearest
    # class with hit points that has none of its own.
    first = {name: min(code) for code, name in spans}
    for name, (health, attack) in list(classes.items()):
        if health or not attack:
            continue
        near = [n for n, (h, a) in classes.items() if h and abs(first[n] - first[name]) < 0x8000]
        if near:
            owner = min(near, key=lambda n: abs(first[n] - first[name]))
            if not classes[owner][1]:
                classes[owner][1].update(attack)
    classes = {k: (sorted(h), sorted(a)) for k, (h, a) in classes.items()}
    return table, classes


def main():
    if len(sys.argv) > 1 and sys.argv[1] != '--emit':
        table, classes = scan(sys.argv[1])
        print(f'combat table at {table:#x}')
        for name, (health, attack) in sorted(classes.items()):
            print(f'  {name:24s} health tiers {health} attack tiers {attack}')
        return
    lines = ['// Generated by tools/sm/sm_enemy_tiers.py --emit from the level modules\' decompilations: the strength tier',
             '// each class reads from its level\'s combat table (hit points, attack). -1: the class reads none.',
             '// {level, class, hit point tier, attack tier}']
    for path in sorted((WORK / 'ghidra').glob('L??_decomp.json')):
        level = path.name[1:3]
        _, classes = scan(level)
        for name, (health, attack) in sorted(classes.items()):
            # a class reading several tiers (a boss with phases, a shot helper shared by two classes) keeps the first
            h, k = OVERRIDES.get((int(level), name), (health[0] if health else -1, attack[0] if attack else -1))
            lines.append(f'{{{int(level)}, "{name}", {h}, {k}}},')
    (ROOT / 'src/sm/enemy_tiers.inl').write_text('\n'.join(lines) + '\n')
    print(len(lines) - 3, 'rows')


if __name__ == '__main__':
    main()
